#!/usr/bin/env python3
"""Finds the hexagons in the grips of NYXI's front-view drawing, so PadArt.qml can redraw them as clean,
identical hexagons instead of the drawing's doubled 3D outlines.

Every hexagon's inside is a small closed pocket between the lines; its centre and height give the hexagon.

Usage: hexes.py <drawing.png> <out Hexes.js> <out hexes.json>
  Hexes.js  - [x, y, radius] per hexagon, drawn by PadArt.qml
  hexes.json - the same, read by trace-art.py ("eraseHexes") to wipe the old hexagons from the trace
Needs: python3 with Pillow.
"""
import collections
import json
import sys

from PIL import Image

GRIPS = [(88, 420, 232, 700), (640, 420, 792, 700)]   # a box around each grip's hexagons
LIMIT = 170                                            # darker than this is line
MIN_AREA, MIN_SIZE = 30, 7                             # an inside is bigger than line noise


def pockets(px, box):
    x0, y0, x1, y1 = box
    seen, found = set(), []
    for y in range(y0, y1):
        for x in range(x0, x1):
            if (x, y) in seen or px[x, y] < LIMIT:
                continue
            todo, cells, touches = collections.deque([(x, y)]), [], False
            seen.add((x, y))
            while todo:
                a, b = todo.popleft()
                cells.append((a, b))
                touches |= a in (x0, x1 - 1) or b in (y0, y1 - 1)
                for n in ((a + 1, b), (a - 1, b), (a, b + 1), (a, b - 1)):
                    if x0 <= n[0] < x1 and y0 <= n[1] < y1 and n not in seen and px[n] >= LIMIT:
                        seen.add(n)
                        todo.append(n)
            if touches or len(cells) < MIN_AREA or len(cells) > 600:
                continue
            xs, ys = [c[0] for c in cells], [c[1] for c in cells]
            w, h = max(xs) - min(xs) + 1, max(ys) - min(ys) + 1
            if w >= MIN_SIZE and h >= MIN_SIZE:
                found.append((sum(xs) / len(xs), sum(ys) / len(ys), h))
    return found


def main():
    src, js, js_json = sys.argv[1:4]
    px = Image.open(src).convert("L").load()
    hexes = []
    for box in GRIPS:
        for x, y, h in pockets(px, box):
            hexes.append([round(x, 1), round(y, 1), round(h / 2 + 2.2, 1)])   # outer radius: inside plus the line
    hexes.sort(key=lambda p: (p[1], p[0]))
    radius = sorted(p[2] for p in hexes)[len(hexes) // 2]      # one size for all, as on the real grip
    hexes = [[x, y, radius] for x, y, _ in hexes]
    with open(js, "w") as f:
        f.write("// Generated by tools/hexes.py from NYXI's line drawing of the Flexi. Do not edit by hand.\n")
        f.write("// One hexagon per entry: centre x, centre y, radius, in drawing coordinates.\n")
        f.write("var HEXES = [\n" + ",\n".join("  [%s,%s,%s]" % tuple(p) for p in hexes) + "\n]\n")
    json.dump(hexes, open(js_json, "w"))
    print(len(hexes), "hexagons, radius", radius)


if __name__ == "__main__":
    main()
