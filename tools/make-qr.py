#!/usr/bin/env python3
"""Makes the QR code PadBack.qml draws on the back of the controller (Qr.js).

Usage: make-qr.py <url> <out Qr.js>
Needs: `qrencode` (the qrencode package) and python3 with Pillow.
"""
import subprocess
import sys
import tempfile

from PIL import Image


def main():
    url, out = sys.argv[1], sys.argv[2]
    with tempfile.NamedTemporaryFile(suffix=".png") as tmp:
        subprocess.run(["qrencode", "-s", "1", "-m", "0", "-l", "M", "-t", "PNG", "-o", tmp.name, url], check=True)
        im = Image.open(tmp.name).convert("L")
    px = im.load()
    rows = ["".join("1" if px[x, y] < 128 else "0" for x in range(im.width)) for y in range(im.height)]
    with open(out, "w") as f:
        f.write("// Generated by tools/make-qr.py. Do not edit by hand.\n")
        f.write("// One string per row, 1 for a dark module.\n")
        f.write("var URL = \"%s\"\n" % url)
        f.write("var ROWS = [\n" + ",\n".join('  "%s"' % r for r in rows) + "\n]\n")
    print(im.width, "x", im.height, "modules")


if __name__ == "__main__":
    main()
